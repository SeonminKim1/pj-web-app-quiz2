import { render } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { CoinBurst } from './CoinBurst.tsx';

afterEach(() => {
  document.body.innerHTML = '';
  vi.restoreAllMocks();
  vi.unstubAllGlobals();
});

it('골드 배지 쪽으로 동전 5개를 날리고, 사라지면 정리한다', () => {
  const badge = document.createElement('span');
  badge.dataset.goldBadge = '';
  document.body.append(badge);
  const animate = vi.fn();
  HTMLElement.prototype.animate = animate as never;
  const { unmount } = render(<CoinBurst />);
  expect(animate).toHaveBeenCalledTimes(5);
  expect(document.body.querySelectorAll('span[class*=coin]')).toHaveLength(5);
  unmount();
  expect(document.body.querySelectorAll('span[class*=coin]')).toHaveLength(0);
});

// Value: protects=동작 줄이기면 동전을 날리지 않는다; fails_when=CoinBurst의 reduce 확인을 빼거나 뒤집으면; why_new=기존 테스트는 matchMedia 없는(움직이는) 쪽만 봄; seam=none; no_claim=CSS 쪽 애니메이션(가짜 matchMedia; 단위만)
// Generated by /ship test coverage audit.
it('동작 줄이기면 동전을 날리지 않는다', () => {
  vi.stubGlobal('matchMedia', () => ({ matches: true }) as MediaQueryList);
  const badge = document.createElement('span');
  badge.dataset.goldBadge = '';
  document.body.append(badge);
  const animate = vi.fn();
  HTMLElement.prototype.animate = animate as never;
  render(<CoinBurst />);
  expect(animate).not.toHaveBeenCalled();
  expect(document.body.querySelectorAll('span[class*=coin]')).toHaveLength(0);
});
